BEGIN;

CREATE TABLE empresa (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome VARCHAR(255) NOT NULL,
                         cnpj VARCHAR(18) NOT NULL UNIQUE,
                         ativa BOOLEAN NOT NULL DEFAULT TRUE,
                         criada_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP
);

CREATE TABLE usuario (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome VARCHAR(255) NOT NULL,
                         email VARCHAR(255) NOT NULL UNIQUE,
                         senha VARCHAR(255) NOT NULL,
                         perfil VARCHAR(20) NOT NULL,
                         empresa_id BIGINT REFERENCES empresa(id),
                         cargo VARCHAR(80),
                         foto_perfil VARCHAR(500),
                         telefone VARCHAR(20),
                         preferencias_notificacao JSONB NOT NULL DEFAULT '{}'::JSONB,
                         CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('CLIENTE', 'SUPORTE', 'ADMIN')),
                         CONSTRAINT ck_usuario_preferencias_objeto CHECK (jsonb_typeof(preferencias_notificacao) = 'object')
);

CREATE TABLE politica_sla (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              prioridade VARCHAR(20) NOT NULL UNIQUE,
                              minutos_primeira_resposta INTEGER NOT NULL,
                              minutos_resolucao INTEGER NOT NULL,
                              CONSTRAINT ck_politica_sla_prioridade CHECK (prioridade IN ('CRITICA', 'ALTA', 'MEDIA', 'BAIXA')),
                              CONSTRAINT ck_politica_sla_prazos CHECK (minutos_primeira_resposta > 0 AND minutos_resolucao > 0)
);

CREATE TABLE avaliacao (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nota_avaliacao INTEGER NOT NULL CHECK (nota_avaliacao BETWEEN 1 AND 5),
                           comentario_avaliacao VARCHAR(500),
                           avaliado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP
);

CREATE TABLE chamado (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         protocolo VARCHAR(20) NOT NULL UNIQUE,
                         titulo VARCHAR(255) NOT NULL,
                         descricao TEXT NOT NULL,
                         duracao_audio_segundos DOUBLE PRECISION CHECK (duracao_audio_segundos >= 0),
                         status VARCHAR(30) NOT NULL DEFAULT 'ABERTO',
    -- Nulos durante a abertura, antes de aplicar a classificacao da IA/fallback.
                         prioridade VARCHAR(20),
                         categoria VARCHAR(30),
                         empresa_id BIGINT NOT NULL REFERENCES empresa(id),
                         solicitante_id BIGINT NOT NULL REFERENCES usuario(id),
                         responsavel_id BIGINT REFERENCES usuario(id),
                         aberto_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
                         primeira_resposta_em TIMESTAMP WITHOUT TIME ZONE,
                         resolvido_em TIMESTAMP WITHOUT TIME ZONE,
                         prazo_primeira_resposta TIMESTAMP WITHOUT TIME ZONE,
    -- Nullable: MELHORIA não possui prazo de SLA.
                         prazo_resolucao TIMESTAMP WITHOUT TIME ZONE,
                         origem VARCHAR(10) NOT NULL DEFAULT 'TEXTO',
                         avaliacao_id BIGINT UNIQUE REFERENCES avaliacao(id),
                         CONSTRAINT ck_chamado_status CHECK (status IN (
                                                                        'ABERTO', 'EM_ANALISE', 'EM_ATENDIMENTO', 'AGUARDANDO_CLIENTE', 'RESOLVIDO', 'FECHADO'
                             )),
                         CONSTRAINT ck_chamado_prioridade CHECK (prioridade IN ('CRITICA', 'ALTA', 'MEDIA', 'BAIXA', 'MELHORIA')),
                         CONSTRAINT ck_chamado_categoria CHECK (categoria IN (
                                                                              'INDISPONIBILIDADE', 'ERRO_FUNCIONAL', 'LENTIDAO', 'ACESSO', 'DUVIDA', 'MELHORIA'
                             )),
                         CONSTRAINT ck_chamado_origem CHECK (origem IN ('TEXTO', 'VOZ'))
);

CREATE TABLE mensagens (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           chamado_id BIGINT NOT NULL REFERENCES chamado(id),
                           usuario_id BIGINT NOT NULL REFERENCES usuario(id),
                           tipo VARCHAR(10) NOT NULL DEFAULT 'TEXTO',
                           conteudo TEXT NOT NULL CHECK (length(trim(conteudo)) > 0),
                           anexo_id BIGINT,
                           visivel_apenas_suporte BOOLEAN NOT NULL DEFAULT FALSE,
                           criado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
                           CONSTRAINT ck_mensagem_tipo CHECK (tipo IN ('TEXTO', 'AUDIO', 'SISTEMA'))
);

CREATE TABLE historico (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           chamado_id BIGINT NOT NULL REFERENCES chamado(id),
                           usuario_id BIGINT REFERENCES usuario(id),
                           valor_anterior VARCHAR(255),
                           valor_novo VARCHAR(255),
                           alterado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP
);

CREATE TABLE classificacao_ia (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  chamado_id BIGINT NOT NULL UNIQUE REFERENCES chamado(id),
                                  categoria_sugerida VARCHAR(30),
                                  prioridade_sugerida VARCHAR(20),
                                  justificativa TEXT,
                                  modelo VARCHAR(50),
                                  titulo_gerado_ia VARCHAR(255),
    -- Síntese estruturada; nullable para classificações anteriores ao enriquecimento.
                                  sintoma_observado_ia TEXT,
                                  impacto_operacional_ia TEXT,
                                  tecnico_sugerido_id BIGINT REFERENCES usuario(id),
                                  sla_meta_minutos INTEGER CHECK (sla_meta_minutos > 0),
                                  categoria_final VARCHAR(30),
                                  prioridade_final VARCHAR(20),
                                  classificada_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
                                  CONSTRAINT ck_classificacao_categoria_sugerida CHECK (categoria_sugerida IN (
                                                                                                               'INDISPONIBILIDADE', 'ERRO_FUNCIONAL', 'LENTIDAO', 'ACESSO', 'DUVIDA', 'MELHORIA'
                                      )),
                                  CONSTRAINT ck_classificacao_categoria_final CHECK (categoria_final IN (
                                                                                                         'INDISPONIBILIDADE', 'ERRO_FUNCIONAL', 'LENTIDAO', 'ACESSO', 'DUVIDA', 'MELHORIA'
                                      )),
                                  CONSTRAINT ck_classificacao_prioridade_sugerida CHECK (prioridade_sugerida IN ('CRITICA', 'ALTA', 'MEDIA', 'BAIXA', 'MELHORIA')),
                                  CONSTRAINT ck_classificacao_prioridade_final CHECK (prioridade_final IN ('CRITICA', 'ALTA', 'MEDIA', 'BAIXA', 'MELHORIA'))
);

CREATE INDEX idx_usuario_empresa ON usuario(empresa_id);
CREATE INDEX idx_chamado_empresa ON chamado(empresa_id);
CREATE INDEX idx_chamado_abertura ON chamado(aberto_em DESC, id DESC);
CREATE INDEX idx_chamado_solicitante_abertura ON chamado(solicitante_id, aberto_em DESC, id DESC);
CREATE INDEX idx_chamado_responsavel_abertura ON chamado(responsavel_id, aberto_em DESC, id DESC);
CREATE INDEX idx_chamado_status_abertura ON chamado(status, aberto_em DESC, id DESC);
CREATE INDEX idx_chamado_prioridade ON chamado(prioridade);
CREATE INDEX idx_chamado_categoria ON chamado(categoria);
CREATE INDEX idx_chamado_origem ON chamado(origem);
CREATE INDEX idx_chamado_prazo_resolucao ON chamado(prazo_resolucao) WHERE resolvido_em IS NULL;
CREATE INDEX idx_chamado_prazo_resposta ON chamado(prazo_primeira_resposta) WHERE primeira_resposta_em IS NULL;
CREATE INDEX idx_mensagem_chamado_envio ON mensagens(chamado_id, criado_em, id);
CREATE INDEX idx_mensagem_usuario ON mensagens(usuario_id);
CREATE INDEX idx_historico_chamado_data ON historico(chamado_id, alterado_em, id);
CREATE INDEX idx_historico_usuario ON historico(usuario_id);

-- Resolução em minutos corridos: Crítica 2h, Alta 4h, Média 12h, Baixa 48h.
-- MELHORIA não tem política nem contagem de SLA.
INSERT INTO politica_sla (prioridade, minutos_primeira_resposta, minutos_resolucao)
VALUES ('CRITICA', 15, 120),
       ('ALTA', 60, 240),
       ('MEDIA', 240, 720),
       ('BAIXA', 480, 2880);

CREATE TABLE anexos (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        chamado_id BIGINT NOT NULL REFERENCES chamado(id),
                        usuario_id BIGINT NOT NULL REFERENCES usuario(id),
                        nome_arquivo VARCHAR(255) NOT NULL CHECK (length(trim(nome_arquivo)) > 0),
                        tipo_conteudo VARCHAR(255),
                        caminho_arquivo VARCHAR(1000) NOT NULL CHECK (length(trim(caminho_arquivo)) > 0),
                        tamanho_bytes BIGINT NOT NULL CHECK (tamanho_bytes > 0),
                        duracao_audio_segundos DOUBLE PRECISION CHECK (duracao_audio_segundos >= 0),
                        enviado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX idx_anexos_chamado_envio ON anexos(chamado_id, enviado_em, id);
CREATE INDEX idx_anexos_usuario ON anexos(usuario_id);

CREATE TABLE pausa_sla (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           chamado_id BIGINT NOT NULL REFERENCES chamado(id),
                           usuario_id BIGINT NOT NULL REFERENCES usuario(id),
                           motivo TEXT NOT NULL CHECK (length(trim(motivo)) > 0),
                           inicio TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT LOCALTIMESTAMP,
                           fim TIMESTAMP WITHOUT TIME ZONE,
                           CONSTRAINT ck_pausa_sla_intervalo CHECK (fim IS NULL OR fim >= inicio)
);
CREATE INDEX idx_pausa_sla_chamado_inicio ON pausa_sla(chamado_id, inicio, id);
CREATE INDEX idx_pausa_sla_usuario ON pausa_sla(usuario_id);

ALTER TABLE mensagens ADD CONSTRAINT fk_mensagem_anexo FOREIGN KEY (anexo_id) REFERENCES anexos(id);
CREATE INDEX idx_mensagem_anexo ON mensagens(anexo_id);

CREATE UNIQUE INDEX uk_usuario_email_normalizado ON usuario (lower(trim(email)));

CREATE TABLE notificacao (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             usuario_id BIGINT NOT NULL REFERENCES usuario(id),
                             chamado_id BIGINT REFERENCES chamado(id),
                             titulo VARCHAR(255) NOT NULL,
                             mensagem TEXT NOT NULL,
                             tipo VARCHAR(30) NOT NULL,
                             lida BOOLEAN NOT NULL DEFAULT FALSE,
                             criado_em TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX idx_notificacao_usuario_data ON notificacao(usuario_id, criado_em DESC, id DESC);
CREATE INDEX idx_notificacao_nao_lida ON notificacao(usuario_id) WHERE NOT lida;
-- Mapeada por LeituraChamado para também ser reconhecida pelo ddl-auto=update.
CREATE TABLE leitura_chamado (
                                 usuario_id BIGINT NOT NULL REFERENCES usuario(id),
                                 chamado_id BIGINT NOT NULL REFERENCES chamado(id),
                                 ultima_mensagem_id BIGINT NOT NULL DEFAULT 0,
                                 PRIMARY KEY(usuario_id, chamado_id)
);

COMMIT;

